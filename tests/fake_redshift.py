"""Test doubles for the Redshift Data API.

* ScriptedDataApi  - returns scripted responses (statuses, pages, errors): tests the notebook's Data API helper functions.
* PgDataApi        - executes the statements on a throw-away PostgreSQL after removing the Redshift-only DDL clauses
                     (ENCODE, DISTKEY, SORTKEY, DISTSTYLE, IDENTITY). This is an EMULATION: it proves the SQL logic and the
                     naming handling, it does not prove that Amazon Redshift accepts the statements.
"""
import re
import uuid
from decimal import Decimal

import botocore.exceptions as _bex  # real botocore when installed, otherwise the stub from nbload


def client_error(code, op="ExecuteStatement"):
    return _bex.ClientError({"Error": {"Code": code, "Message": code}}, op)


class ScriptedDataApi:
    """execute_statement / describe_statement / get_statement_result / cancel_statement with scripted behaviour."""

    def __init__(self, statuses=("FINISHED",), pages=None, execute_error=None, error_text="boom", has_result=True):
        self.statuses = list(statuses)
        self.pages = pages or []
        self.execute_error = execute_error
        self.error_text = error_text
        self.has_result = has_result
        self.executed, self.cancelled, self.polls, self.page_tokens = [], [], 0, []

    def execute_statement(self, Sql, **kw):
        if self.execute_error:
            raise self.execute_error
        self.executed.append(Sql)
        return {"Id": "stmt-1"}

    def describe_statement(self, Id):
        status = self.statuses[min(self.polls, len(self.statuses) - 1)]
        self.polls += 1
        d = {"Id": Id, "Status": status, "Duration": 5_000_000, "HasResultSet": self.has_result}
        if status == "FAILED":
            d["Error"] = self.error_text
        return d

    def cancel_statement(self, Id):
        self.cancelled.append(Id)

    def get_statement_result(self, Id, NextToken=None):
        self.page_tokens.append(NextToken)
        idx = int(NextToken) if NextToken else 0
        page = dict(self.pages[idx])
        if idx + 1 < len(self.pages):
            page["NextToken"] = str(idx + 1)
        return page


def redshift_to_pg(sql: str) -> str:
    """Remove the Redshift-only clauses of a CREATE TABLE so that PostgreSQL accepts it."""
    if not re.match(r"\s*CREATE TABLE", sql, re.I):
        return sql
    sql = re.sub(r"\bENCODE\s+\w+", "", sql, flags=re.I)
    sql = re.sub(r"\bDISTSTYLE\s+\w+", "", sql, flags=re.I)
    sql = re.sub(r"\bDISTKEY\s*\([^)]*\)", "", sql, flags=re.I)
    sql = re.sub(r"\bSORTKEY\s*\([^)]*\)", "", sql, flags=re.I)
    return re.sub(r"\bIDENTITY\s*\(\s*\d+\s*,\s*\d+\s*\)", "GENERATED BY DEFAULT AS IDENTITY", sql, flags=re.I)


def _field(v):
    if v is None:
        return {"isNull": True}
    if isinstance(v, bool):
        return {"booleanValue": v}
    if isinstance(v, int):
        return {"longValue": v}
    if isinstance(v, float):
        return {"doubleValue": v}
    return {"stringValue": str(v)}


def _type_name(v):
    return {bool: "bool", int: "int8", float: "float8", Decimal: "numeric"}.get(type(v), "varchar")


class PgDataApi:
    def __init__(self, dsn, dbname=None, deny_create_schema=False, page_size=1000):
        import psycopg2
        self.psycopg2 = psycopg2
        from pgserver import dsn_with
        self.conn = psycopg2.connect(dsn_with(dsn, dbname))
        self.conn.autocommit = True
        self.deny_create_schema = deny_create_schema
        self.page_size = page_size
        self.stmts, self.log = {}, []

    def execute_statement(self, Sql, **kw):
        sid = uuid.uuid4().hex
        self.log.append(Sql)
        try:
            if self.deny_create_schema and re.match(r"\s*CREATE SCHEMA", Sql, re.I):
                raise self.psycopg2.errors.InsufficientPrivilege("permission denied for database ecom")
            with self.conn.cursor() as cur:
                cur.execute(redshift_to_pg(Sql))
                if cur.description:
                    names = [d.name for d in cur.description]
                    rows = cur.fetchall()
                    self.stmts[sid] = dict(Status="FINISHED", HasResultSet=True, Duration=1_000_000, names=names, rows=rows)
                else:
                    self.stmts[sid] = dict(Status="FINISHED", HasResultSet=False, Duration=1_000_000)
        except Exception as e:  # noqa: BLE001 - the Data API reports every failure as a FAILED statement
            self.stmts[sid] = dict(Status="FAILED", HasResultSet=False, Duration=0, Error=str(e).strip())
        return {"Id": sid}

    def describe_statement(self, Id):
        d = self.stmts[Id]
        return {k: v for k, v in d.items() if k not in ("names", "rows")} | {"Id": Id}

    def cancel_statement(self, Id):
        pass

    def get_statement_result(self, Id, NextToken=None):
        d = self.stmts[Id]
        start = int(NextToken or 0)
        chunk = d["rows"][start:start + self.page_size]
        first = d["rows"][0] if d["rows"] else [None] * len(d["names"])
        meta = [{"name": n, "label": n, "typeName": _type_name(v)} for n, v in zip(d["names"], first)]
        page = {"ColumnMetadata": meta, "Records": [[_field(v) for v in r] for r in chunk]}
        if start + self.page_size < len(d["rows"]):
            page["NextToken"] = str(start + self.page_size)
        return page

    def close(self):
        self.conn.close()
